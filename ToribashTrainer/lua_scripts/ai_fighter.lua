local combo_names = {
    "Aikido Throw", "Power Rush", "Combo Breaker", "Judo Hip Toss",
    "Flying Kick", "Spin Sweep", "Grapple Slam", "Double Grab",
    "Grab & Kick", "Wushu Strike", "Tornado", "Knee Strike",
    "Side Kick", "Quick Jab", "Leg Sweep",
}

-- Apply one turn of a combo
-- Format: {grip_r, grip_l, j0, j1, j2, ... j19}
local function do_move()
    move = move + 1
    local c = combos[chosen]
    if c == nil then
        chosen = math.random(1, #combos)
        move = 1
        c = combos[chosen]
    end

    local turn = c[move]
    if turn == nil then
        -- Combo finished, pick new one
        chosen = math.random(1, #combos)
        move = 1
        turn = combos[chosen][1]
        echo("[AI] Switching to: " .. (combo_names[chosen] or "?"))
    end

    if turn == nil then return end

    -- turn[1]=grip_r, turn[2]=grip_l, turn[3..22]=joints 0..19
    for j = 0, 19 do
        local state = turn[j + 3]
        if state ~= nil then
            set_joint_state(0, j, state)
        end
    end

    -- Set grips if the function exists
    if set_grip_info ~= nil then
        if turn[1] ~= nil then set_grip_info(0, 11, turn[1]) end
        if turn[2] ~= nil then set_grip_info(0, 12, turn[2]) end
    end
end

-- Same move again on exit_freeze (reinforces the move)
local function redo_move()
    local c = combos[chosen]
    if c == nil then return end
    local turn = c[move]
    if turn == nil then return end

    for j = 0, 19 do
        local state = turn[j + 3]
        if state ~= nil then
            set_joint_state(0, j, state)
        end
    end

    if set_grip_info ~= nil then
        if turn[1] ~= nil then set_grip_info(0, 11, turn[1]) end
        if turn[2] ~= nil then set_grip_info(0, 12, turn[2]) end
    end
end

-- New round: pick a combo
local function new_round()
    chosen = math.random(1, #combos)
    move = 0
    echo("[AI] Round start: " .. (combo_names[chosen] or ("Combo #" .. chosen)))
    do_move()
end

